"""Recreate isolated, editable prototype nature assets in Blender 5.2.

The underlying meshes are generated by ../../nature.py.  Re-running this file
overwrites the three generated .blend files in this directory.
"""
import os
import sys
import bpy

ASSET_DIR = os.path.dirname(os.path.abspath(__file__))
SOURCE_DIR = os.path.abspath(os.path.join(ASSET_DIR, '..', '..'))
sys.path.insert(0, SOURCE_DIR)
import nature

bpy.context.preferences.filepaths.save_version = 0

def clear_scene():
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete(use_global=False)
    bpy.context.scene.unit_settings.system = 'METRIC'

def material(name, color):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1.0)
    mat.use_nodes = True
    p = mat.node_tree.nodes.get('Principled BSDF')
    p.inputs['Base Color'].default_value = (*color, 1.0)
    p.inputs['Roughness'].default_value = .8
    return mat

for filename, kind, seed in (
    ('Dead_Tree_01_Prototype.blend', 'tree', 100),
    ('Dead_Tree_02_Prototype.blend', 'tree', 109),
    ('Grave_Marker_Prototype.blend', 'grave', None),
):
    clear_scene()
    materials = {
        'bark': material('Trees - black bark', (.065, .07, .085)),
        'stone': material('Stone - slate', (.18, .205, .24)),
    }
    if kind == 'tree':
        obj = nature.create_tree((0, 0, 0), 0, 1, materials, seed)
        obj.name = 'Prototype_Dead_Tree'
    else:
        obj = nature.create_grave((0, 0, 0), 0, 1, materials)
        obj.name = 'Prototype_Grave_Marker'
    obj['stage'] = 'Visual prototype; not game-ready'
    assert obj.type == 'MESH' and len(obj.data.polygons) > 0
    assert tuple(obj.location) == (0, 0, 0)
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(ASSET_DIR, filename))
    print('SAVED', filename, len(obj.data.vertices), len(obj.data.polygons))
